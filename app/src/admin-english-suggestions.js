export function normalizedFrenchTitle(value){
  if(typeof value!=="string")return "";
  // Retirer uniquement les marques Unicode et la ponctuation typographique,
  // sans interpréter un mot isolé comme une phrase libre.
  return value.normalize("NFKC").toLocaleLowerCase("fr-CA")
    .replace(/[’‘]/g,"'").normalize("NFD").replace(/[\u0300-\u036f]/g,"")
    .replace(/[\u2010-\u2015-]/g," ").trim().replace(/\s+/g," ");
}

export function suggestEnglishTitle(titleFr){
  const key=normalizedFrenchTitle(titleFr);
  if(!key||key.length>100)return "";
  // Pict-au : les libellés commencent par une minuscule.
  // Le pronom anglais I garde obligatoirement sa majuscule.
  return key==="j'ai besoin d'aide"?"I need help":
    (translations[key]||"").toLocaleLowerCase("en-CA");
}
